def main():
    """批量生成法律规则配置文件"""
    base_dir = Path(__file__).resolve().parent.parent / "references" / "rule-packs"

    # 确保目录存在
    base_dir.mkdir(parents=True, exist_ok=True)

    count = 0
    for contract_type, rules in LEGAL_RULES.items():
        # 创建目录
        type_dir = base_dir / contract_type
        type_dir.mkdir(parents=True, exist_ok=True)

        # 写入规则文件
        rule_file = type_dir / "legal_rules.json"
        with open(rule_file, 'w', encoding='utf-8') as f:
            json.dump(rules, f, ensure_ascii=False, indent=2)

        count += 1
        print(f"✅ {contract_type} 规则已生成")

    print(f"\n总计生成 {count} 个法律规则配置文件")
    print(f"保存路径: {base_dir}")


if __name__ == '__main__':
    main()
