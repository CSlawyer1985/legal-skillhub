def basis_lead(pages: list[str], form_page: int, next_form_page: int) -> str:
    segment = normalize("\n".join(pages[form_page - 1:max(form_page + 1, next_form_page - 1)]))
    match = re.search(r"【说明】(.{0,1200}?)(?:【应用】|【法律依据】)", segment)
    return match.group(1)[:1200] if match else "OCR未完整提取说明，须回到标注页人工核对"


def purpose(name: str) -> str:
    match = re.search(r"（(.+?)）", name)
    text = match.group(1) if match else name
    return text[:-1] if text.endswith("用") else text


