def parts(value: str) -> list[str]:
    return [item.strip() for item in value.split("；") if item.strip()]


def module(
    claim_id: str,
    name: str,
    relief: str,
    elements: str,
    facts: str,
    evidence: str,
    defenses: str,
    review: str,
    calculation: str = "不涉及独立金额计算；核对请求内容是否明确、可判和可执行。",
    conflicts: str = "",
    branch: str = "standard",
) -> dict:
    fact_questions = [
        {
            "question_id": f"{claim_id}-F{index:02d}",
            "prompt": prompt,
            "blocking": True,
        }
        for index, prompt in enumerate(parts(facts), 1)
    ]
    evidence_groups = [
        {
            "evidence_id": f"{claim_id}-E{index:02d}",
            "group": item,
            "required_or_explain_absence": True,
        }
        for index, item in enumerate(parts(evidence), 1)
    ]
    return {
        "claim_id": claim_id,
        "request_name": name,
        "relief_type": relief,
        "branch": branch,
        "elements": parts(elements),
        "fact_questions": fact_questions,
        "evidence_groups": evidence_groups,
        "defense_paths": parts(defenses),
        "court_review_checks": parts(review),
        "calculation_rule": calculation,
        "conflicts_with": parts(conflicts),
        "drafting_rule": "请求写明义务主体、给付或行为内容、金额或范围、起止时点、履行方式和费用负担；事实、证据和理由逐要件对应。",
    }


