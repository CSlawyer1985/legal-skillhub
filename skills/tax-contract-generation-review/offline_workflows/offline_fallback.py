def get_template_by_type(contract_type: str) -> Optional[Dict[str, Any]]:
    """Get contract template by type name."""
    for category, templates in CONTRACT_TEMPLATES.items():
        if contract_type in templates:
            template = templates[contract_type]
            return {
                "category": category,
                **template,
            }
    return None


def search_templates(keyword: str) -> List[Dict[str, Any]]:
    """Search contract templates by keyword."""
    results = []
    keyword_lower = keyword.lower()
    for category, templates in CONTRACT_TEMPLATES.items():
        for name, template in templates.items():
            if keyword_lower in name.lower() or keyword_lower in template.get("适用场景", "").lower():
                results.append({
                    "category": category,
                    "name": name,
                    **template,
                })
    return results


def get_all_templates() -> Dict[str, Any]:
    """Get all contract templates organized by category."""
    return CONTRACT_TEMPLATES


def get_tax_summary() -> str:
    """Get contract type and tax summary."""
    lines = [
        "# 合同类型与税种对照速查表",
        "",
        "| 合同类型 | 印花税税目 | 印花税税率 | 增值税税率(一般) |",
        "|----------|-----------|-----------|-----------------|",
    ]
    for category, templates in CONTRACT_TEMPLATES.items():
        for name, template in templates.items():
            tax = template.get("税种", {})
            stamp = tax.get("印花税", "—")
            vat = tax.get("增值税", "—")
            lines.append(f"| {name} | — | {stamp} | {vat} |")
    return "\n".join(lines)


