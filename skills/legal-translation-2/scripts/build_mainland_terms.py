OUTPUT_PATH = os.path.join(SKILL_DIR, 'references', 'mainland_terms.csv')

def main():
    # 去重（同 (CN, EN) 只保留一条）
    seen = set()
    unique_terms = []
    for cn, en, src, dom, typ in TERMS:
        key = (cn, en)
        if key not in seen:
            seen.add(key)
            unique_terms.append((cn, en, src, dom, typ))

    # 排序：先按领域，再按中文
    domain_order = {'民法': 0, '刑法': 1, '商法': 2, '诉讼法': 3, '宪法行政法': 4}
    unique_terms.sort(key=lambda t: (domain_order.get(t[3], 99), t[0]))

    # 写入 CSV
    with open(OUTPUT_PATH, 'w', encoding='utf-8-sig', newline='') as f:
        writer = csv.writer(f)
        writer.writerow(['中文词语', '英文词语', '来源', '领域', '类型'])
        writer.writerows(unique_terms)

    # 统计
    domains = {}
    types = {}
    for t in unique_terms:
        domains[t[3]] = domains.get(t[3], 0) + 1
        types[t[4]] = types.get(t[4], 0) + 1

    print(f"大陆法律术语总数: {len(unique_terms)}")
    print(f"\n领域分布:")
    for k, v in sorted(domains.items(), key=lambda x: -x[1]):
        print(f"  {k}: {v}")
    print(f"\n类型分布:")
    for k, v in sorted(types.items(), key=lambda x: -x[1]):
        print(f"  {k}: {v}")
    print(f"\n输出: {OUTPUT_PATH}")


if __name__ == '__main__':
    main()
